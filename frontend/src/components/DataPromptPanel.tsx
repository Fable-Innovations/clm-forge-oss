import { useMemo, useState } from "react";
import { Check, ChevronDown, ClipboardCopy, Database } from "lucide-react";
import type { Opportunity, TaskSchema } from "../api/types";
import { dataExportPrompt } from "../lib/dataPrompt";
import { cn } from "../lib/format";
import { Button, Panel } from "./ui";

/** Copy-paste prompt for a coding agent that exports real labelled rows into clm_data/ for curation. */
export function DataPromptPanel({ task, opp, repo, accepted = false }: { task: TaskSchema; opp: Pick<Opportunity, "files" | "target_examples"> | null; repo?: string | null; accepted?: boolean }) {
  const [copied, setCopied] = useState(false);
  const [open, setOpen] = useState(false);
  const text = useMemo(() => dataExportPrompt(task, opp, repo), [task, opp, repo]);
  const copy = async () => {
    try {
      await navigator.clipboard.writeText(text);
    } catch {
      const ta = document.createElement("textarea");
      ta.value = text;
      document.body.appendChild(ta);
      ta.select();
      document.execCommand("copy");
      ta.remove();
    }
    setCopied(true);
    setTimeout(() => setCopied(false), 1800);
  };
  return (
    <Panel
      title={
        <span className="inline-flex items-center gap-2">
          <Database size={14} className="text-muted" /> Train on real data (optional)
        </span>
      }
      sub={
        accepted ? (
          <>
            Hand this prompt to a coding agent in the repo: it exports labelled rows from your database into <span className="font-mono">clm_data/</span>. Tables exported now are imported the next time this project recurates (into train/val; the test split stays frozen) and by every new project on this repo.
          </>
        ) : (
          <>
            Without exports, every example is generated by the LLM, including the test split. Hand this prompt to a coding agent in the repo: it exports labelled rows from your database into <span className="font-mono">clm_data/</span>. Do it before accepting so real rows can fill the test split.
          </>
        )
      }
    >
      <div className="flex items-center gap-2">
        <Button size="sm" variant="secondary" icon={copied ? <Check size={13} /> : <ClipboardCopy size={13} />} onClick={copy}>
          {copied ? "Copied" : "Copy prompt for data agent"}
        </Button>
        <button onClick={() => setOpen((x) => !x)} className="inline-flex items-center gap-1 text-[12.5px] font-medium text-accent cursor-pointer" aria-expanded={open}>
          <ChevronDown size={14} className={cn("transition-transform", !open && "-rotate-90")} />
          {open ? "Hide prompt" : "Show prompt"}
        </button>
      </div>
      {open && <pre className="mt-3 max-h-[420px] overflow-auto whitespace-pre-wrap text-[12px] leading-[1.5] font-mono bg-sunken border border-line-soft rounded-[6px] p-3">{text}</pre>}
    </Panel>
  );
}
